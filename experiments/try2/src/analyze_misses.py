#!/usr/bin/env python3
"""analyze_misses.py — Phase 0, Step 4: where the recall went.

Consumes the annotated pool from build_pool + ground truth, and reports:

  1. DECOMPOSITION  — of all GT pairs: in-pool & rank<K (delivered at K=80),
                      in-pool but rank>=K (CAPPED OUT by top-K), or absent
                      from stage-A entirely (NEVER GENERATED by keys).
  2. RECALL@K       — one annotated pass, many K: {25,50,80,150,300,500}
                      pair recall + entity-level all-found rate, overall,
                      per country, and split by counterpart script.
  3. TAXONOMY       — for every GT pair NOT delivered at K=80, the first
                      matching explanation, in priority order:
                        EXACT_NAME   canonical names identical (should be
                                     impossible to miss -> key/bucket bug)
                        HN_AND_STATE house number + state both equal
                        TRANSITIVE   shares exact canonical name with another
                                     GT record of the same entity
                        NONLATIN     counterpart name is non-Latin (needs
                                     transliteration — Phase 1)
                        SHARED_TOKEN >=1 shared name token (len>=4)
                        INITIALS     acronym/initials agree (len>=3)
                        ADDRESS      house number or state or addr token ok
                        NONE         nothing matched — truly fuzzy
                      plus side-by-side raw record examples per category.
  4. TRY1 CROSS-TAB — (optional, --try1-cache) of try1's missed pairs, how
                      many the new pool would recover.

Writes experiments/try2/output/phase0_report.txt and prints it.
Train only (GT required).
"""

from __future__ import annotations

import os as _os, sys as _sys  # un-shadow stdlib 'inspect' (this dir has inspect.py)
_src_d = _os.path.dirname(_os.path.abspath(__file__))
if _sys.path and _os.path.abspath(_sys.path[0] or _os.getcwd()) == _src_d:
    _sys.path.pop(0)
    _sys.path.append(_src_d)

import argparse
import json
import time
from pathlib import Path

import numpy as np

import normalize as N

KS = (25, 50, 80, 150, 300, 500)
PRIMARY_K = 80
CATS = ["EXACT_NAME", "HN_AND_STATE", "TRANSITIVE", "NONLATIN",
        "SHARED_TOKEN", "INITIALS", "ADDRESS", "NONE"]


def line_offsets(path: Path, cache_dir: Path, stem: str,
                 expect_rows: int) -> np.ndarray:
    out = cache_dir / f"{stem}__lineofs.npy"
    if out.is_file():
        a = np.load(out)
    else:
        offs = []
        with open(path, "rb") as f:
            f.readline()
            while True:
                o = f.tell()
                line = f.readline()
                if not line:
                    break
                offs.append(o)
        a = np.asarray(offs, np.int64)
        np.save(out, a)
    if len(a) != expect_rows:
        print(f"[analyze] WARNING: {stem} line offsets ({len(a):,}) != cache "
              f"rows ({expect_rows:,}) — examples may misalign", flush=True)
    return a


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    N.add_common_args(ap)
    ap.add_argument("--split", default="train", choices=["train", "test"])
    ap.add_argument("--examples", type=int, default=6,
                    help="side-by-side examples per taxonomy category")
    ap.add_argument("--try1-cache", type=Path, default=None,
                    help="try1 cache dir (for the candidates cross-tab)")
    args = ap.parse_args()

    t0 = time.time()
    cd = args.cache_dir
    meta_path = cd / f"{args.split}_pool_meta.json"
    if not meta_path.is_file():
        raise SystemExit(f"missing {meta_path} — run build_pool first")
    meta = json.loads(meta_path.read_text())
    bin_bits = int(meta["bin_bits"])
    n_bins = int(meta["n_bins"])
    counts = json.loads((cd / f"{args.split}_blocking_counts.json").read_text())
    print(f"[analyze] pool mode={meta['mode']} total={meta['pool_total']:,} "
          f"bins={n_bins}", flush=True)

    # ---- GT -------------------------------------------------------------
    gt_path = args.dataset / "train" / "train_ground_truth.tsv"
    if not gt_path.is_file():
        raise SystemExit(f"missing {gt_path}")
    s1l, otl = [], []
    for s1, ids in N.stream_ground_truth(gt_path):
        for c in ids:
            s1l.append(s1)
            otl.append(c)
    gt_s1 = np.asarray(s1l, np.int64)
    gt_ot = np.asarray(otl, np.int64)
    del s1l, otl
    p_gt = (gt_s1 << 33) | gt_ot
    order = np.argsort(p_gt, kind="stable")
    p_gt, gt_s1, gt_ot = p_gt[order], gt_s1[order], gt_ot[order]
    del order
    n_gt = len(p_gt)
    print(f"[analyze] GT pairs: {n_gt:,} ({time.time()-t0:.0f}s)", flush=True)

    # ---- membership + rank from annotated pool --------------------------
    found = np.zeros(n_gt, bool)
    rank = np.full(n_gt, 65535, np.uint32)
    for b in range(n_bins):
        nb = int(meta["bins"][b]["n"])
        if nb == 0:
            continue
        rp = cd / f"{args.split}_pool_bin{b:02d}_rank.u16"
        if not rp.is_file() or rp.stat().st_size != nb * 2:
            raise SystemExit(f"[analyze] {rp.name} missing/wrong size — "
                             f"run build_pool to completion first")
        pp = np.memmap(cd / f"{args.split}_pool_bin{b:02d}.p64",
                       dtype=np.int64, mode="r", shape=(nb,))
        ra = np.fromfile(rp, dtype=np.uint16)
        lo_e = (b << bin_bits) << 33
        hi_e = ((b + 1) << bin_bits) << 33
        lo = int(np.searchsorted(p_gt, lo_e))
        hi = int(np.searchsorted(p_gt, hi_e))
        if hi <= lo:
            del pp
            continue
        gp = p_gt[lo:hi]
        pos = np.searchsorted(pp, gp)
        cp = np.clip(pos, 0, nb - 1)
        ok = (pos < nb) & (pp[cp] == gp)
        found[lo:hi] = ok
        rank[lo:hi] = np.where(ok, ra[cp].astype(np.uint32), 65535)
        del pp
    print(f"[analyze] pool membership scanned ({time.time()-t0:.0f}s)",
          flush=True)

    hit80 = found & (rank < PRIMARY_K)
    n_stage_a_miss = int((~found).sum())
    n_capped = int((found & ~hit80).sum())
    n_delivered = int(hit80.sum())

    # ---- splits ---------------------------------------------------------
    caches = {i: N.SourceCache(cd / f"{args.split}_source{i}")
              for i in (1, 2, 3)}
    r1 = caches[1].row_of(gt_s1)
    cty = caches[1].arrays["country"][np.maximum(r1, 0)]
    ok1 = r1 >= 0
    m2 = gt_ot < N.S3_OFFSET
    script_o = np.zeros(n_gt, np.uint8)
    if m2.any():
        rr = caches[2].row_of(gt_ot[m2])
        script_o[m2] = caches[2].arrays["name_script"][np.maximum(rr, 0)]
    if (~m2).any():
        rr = caches[3].row_of(gt_ot[~m2] - N.S3_OFFSET)
        script_o[~m2] = caches[3].arrays["name_script"][np.maximum(rr, 0)]
    nonlat = script_o != 0

    uniq_s1, starts, cnts = np.unique(gt_s1, return_index=True,
                                      return_counts=True)
    n_ent = len(uniq_s1)
    cty_e = cty[starts]

    def entity_all_found(mask_pair: np.ndarray) -> np.ndarray:
        hits = np.add.reduceat(mask_pair.astype(np.int64), starts)
        return hits == cnts

    # ---- report scaffolding --------------------------------------------
    lines = []

    def L(s=""):
        lines.append(s)
        print(s, flush=True)

    L("=" * 74)
    L(f"PHASE 0 REPORT — split={args.split} — pool mode {meta['mode']} — "
      f"{meta['pool_total']:,} candidates")
    L("=" * 74)
    d = meta["decision"]
    L(f"decision: post-cap total {d['post_cap_total']:,} vs max "
      f"{d['max_volume']:,} -> scale {d['scale']:.4f}")
    L(f"per-key cap {meta['per_key_cap']} (unchanged); bins={n_bins} "
      f"(s1_max={meta['s1_max']:,})")
    L()
    L(f"--- 1. DECOMPOSITION of GT pairs (at K={PRIMARY_K}) ---")
    L(f"  delivered (in pool, rank<{PRIMARY_K}): {n_delivered:,} "
      f"({n_delivered/n_gt*100:.2f}%)")
    L(f"  CAPPED OUT (in pool, rank>={PRIMARY_K}): {n_capped:,} "
      f"({n_capped/n_gt*100:.2f}%)   <- fixed by raising K")
    L(f"  NEVER GENERATED (not in stage-A):        {n_stage_a_miss:,} "
      f"({n_stage_a_miss/n_gt*100:.2f}%)   <- fixed by keys/budget/translit")
    L()
    L("--- 2. RECALL@K (pair recall / entity all-found) ---")
    L(f"  {'K':>5s} {'pair-recall':>12s} {'entity-all-found':>18s} "
      f"{'[US]':>10s} {'[India]':>10s} {'[non-Latin part.]':>19s}")
    for K in KS:
        hit = found & (rank < K)
        pr = hit.mean() * 100
        er = entity_all_found(hit).mean() * 100
        usm = ok1 & (cty == 0)
        inm = ok1 & (cty == 1)
        r_us = hit[usm].mean() * 100 if usm.any() else float("nan")
        r_in = hit[inm].mean() * 100 if inm.any() else float("nan")
        r_nl = hit[nonlat].mean() * 100 if nonlat.any() else float("nan")
        L(f"  {K:>5d} {pr:>11.2f}% {er:>17.2f}% {r_us:>9.2f}% "
          f"{r_in:>9.2f}% {r_nl:>18.2f}%")
    L()
    L(f"  GT entities: {n_ent:,}   entity all-found@"
      f"{PRIMARY_K}: {entity_all_found(hit80).mean()*100:.2f}%")
    L()

    # ---- taxonomy over failures ----------------------------------------
    fail = ~hit80
    n_fail = int(fail.sum())
    L(f"--- 3. TAXONOMY of {n_fail:,} GT pairs not delivered at "
      f"K={PRIMARY_K} ---")
    L("  priority order: " + " > ".join(CATS))
    idx = np.flatnonzero(fail)
    r1f = r1[idx]
    m2f = m2[idx]
    ot_f = gt_ot[idx]

    def other_col(col: str) -> np.ndarray:
        dt = caches[1].arrays[col].dtype
        out = np.zeros(len(idx), dt)
        rr2 = np.zeros(len(idx), np.int64)
        rr3 = np.zeros(len(idx), np.int64)
        if m2f.any():
            rr2[m2f] = caches[2].row_of(ot_f[m2f])
        if (~m2f).any():
            rr3[~m2f] = caches[3].row_of(ot_f[~m2f] - N.S3_OFFSET)
        if m2f.any():
            out[m2f] = caches[2].arrays[col][np.maximum(rr2[m2f], 0)]
        if (~m2f).any():
            out[~m2f] = caches[3].arrays[col][np.maximum(rr3[~m2f], 0)]
        invalid = np.zeros(len(idx), bool)
        if m2f.any():
            invalid[m2f] = rr2[m2f] < 0
        if (~m2f).any():
            invalid[~m2f] = rr3[~m2f] < 0
        if invalid.any():
            out[invalid] = b""
        return N.decode_str(out)

    ns1 = N.decode_str(caches[1].arrays["name_sorted"][np.maximum(r1f, 0)])
    ns1[r1f < 0] = ""
    nso = other_col("name_sorted")
    hn1 = N.decode_str(caches[1].arrays["houseno"][np.maximum(r1f, 0)])
    hno = other_col("houseno")
    st1 = N.decode_str(caches[1].arrays["state"][np.maximum(r1f, 0)])
    sto = other_col("state")
    ini1 = N.decode_str(caches[1].arrays["name_initials"][np.maximum(r1f, 0)])
    inio = other_col("name_initials")
    at1 = N.decode_str(caches[1].arrays["addr_tokens"][np.maximum(r1f, 0)])
    ato = other_col("addr_tokens")
    nonlat_f = nonlat[idx]

    # transitive set: (s1, canonical name) -> partner record ids of that entity
    o_ns_full = np.zeros(n_gt, caches[1].arrays["name_sorted"].dtype)
    m2g = gt_ot < N.S3_OFFSET
    if m2g.any():
        rr = caches[2].row_of(gt_ot[m2g])
        o_ns_full[m2g] = caches[2].arrays["name_sorted"][np.maximum(rr, 0)]
    if (~m2g).any():
        rr = caches[3].row_of(gt_ot[~m2g] - N.S3_OFFSET)
        o_ns_full[~m2g] = caches[3].arrays["name_sorted"][np.maximum(rr, 0)]
    o_ns_full = N.decode_str(o_ns_full)
    from collections import defaultdict
    pmap = defaultdict(list)
    for a, pid, b in zip(gt_s1.tolist(), gt_ot.tolist(), o_ns_full.tolist()):
        pmap[(a, b)].append(pid)
    del o_ns_full

    def is_transitive(s1_id: int, other_id: int, ns: str) -> bool:
        # true only if ANOTHER record of the same entity shares this name AND
        # that record's pair is already delivered (so key-propagation would
        # recover this one). Self-match excluded — that would be vacuous.
        plist = pmap.get((s1_id, ns))
        if not plist:
            return False
        base = s1_id << 33
        for pid in plist:
            if pid == other_id:
                continue
            g = int(np.searchsorted(p_gt, base | pid))
            if g < n_gt and p_gt[g] == (base | pid) and hit80[g]:
                return True
        return False

    cat = np.full(len(idx), -1, np.int8)
    remaining = np.ones(len(idx), bool)

    def assign(code: int, mask: np.ndarray):
        nonlocal remaining
        m = remaining & mask
        cat[m] = code
        remaining &= ~m

    assign(0, (ns1 == nso) & (ns1 != ""))
    assign(1, (hn1 == hno) & (hn1 != "") & (st1 == sto) & (st1 != ""))
    ot_f_list = ot_f.tolist()
    s1f_list = gt_s1[idx].tolist()
    trans_m = np.fromiter(
        (is_transitive(a, pid, b)
         for a, pid, b in zip(s1f_list, ot_f_list, nso.tolist())),
        bool, len(idx))
    del pmap
    assign(2, trans_m & (nso != ""))
    assign(3, nonlat_f)

    tok_m = np.zeros(len(idx), bool)
    for j in np.flatnonzero(remaining):
        ta, tb = ns1[j].split(), nso[j].split()
        if ta and tb:
            sa = {t for t in ta if len(t) >= 4}
            sb = {t for t in tb if len(t) >= 4}
            tok_m[j] = bool(sa & sb)
    assign(4, tok_m)
    assign(5, (ini1 == inio) & (ini1 != "")
              & (np.char.str_len(ini1) >= 3))

    addr_m = ((hn1 == hno) & (hn1 != "")) | ((st1 == sto) & (st1 != ""))
    for j in np.flatnonzero(remaining & ~addr_m):
        ta = {t for t in at1[j].split() if len(t) >= 4}
        tb = {t for t in ato[j].split() if len(t) >= 4}
        if ta & tb:
            addr_m[j] = True
    assign(6, addr_m)
    assign(7, remaining)

    L()
    L(f"  {'category':16s} {'count':>10s} {'% of fails':>11s}  "
      f"{'stage-A-miss':>13s} {'capped@K':>9s}")
    stage_a_miss_arr = ~found[idx]
    for ci, name in enumerate(CATS):
        m = cat == ci
        L(f"  {name:16s} {int(m.sum()):>10,} {m.mean()*100:>10.2f}%  "
          f"{int((m & stage_a_miss_arr).sum()):>13,} "
          f"{int((m & ~stage_a_miss_arr).sum()):>9,}")
    L()

    # ---- side-by-side examples -----------------------------------------
    show = max(0, min(args.examples, 6))
    src_files = {i: args.dataset / "train" / f"{args.split}_source{i}.tsv"
                 for i in (1, 2, 3)}
    offs = {i: line_offsets(p, cd, f"{args.split}_source{i}",
                            caches[i].rows)
            for i, p in src_files.items()}
    handles = {i: open(p, "rb") for i, p in src_files.items()}

    def raw_line(side: int, row: int) -> str:
        if row < 0 or row >= len(offs[side]):
            return "<row out of range>"
        h = handles[side]
        h.seek(int(offs[side][row]))
        return h.readline().decode("utf-8", "replace").rstrip("\n")

    if show:
        L(f"  side-by-side examples (first {show} per category):")
        for ci, name in enumerate(CATS):
            members = idx[cat == ci][:show]
            if len(members) == 0:
                continue
            L(f"\n  [{name}]")
            for gi in members:
                gi = int(gi)
                s1row = int(r1[gi])
                o_id = int(gt_ot[gi])
                if o_id < N.S3_OFFSET:
                    orow = int(caches[2].row_of(
                        np.array([o_id], np.int64))[0])
                    oline = raw_line(2, orow)
                else:
                    orow = int(caches[3].row_of(
                        np.array([o_id - N.S3_OFFSET], np.int64))[0])
                    oline = raw_line(3, orow)
                tag = ("stageA-miss" if not found[gi]
                       else f"capped rank={int(rank[gi])}")
                L(f"    ({tag})  S1 : "
                  + raw_line(1, s1row).replace("\t", " | "))
                L(f"              OTH: " + oline.replace("\t", " | "))
    for h in handles.values():
        h.close()
    L()

    # ---- try1 cross-tab -------------------------------------------------
    if args.try1_cache and (args.try1_cache /
                            f"candidates_{args.split}.npz").is_file():
        import blocking as B
        t1_s1, t1_ind, t1_oth = B.load_candidates(args.try1_cache, args.split)
        cand = np.zeros(n_gt, bool)
        pos_u = np.searchsorted(t1_s1, uniq_s1)
        if len(t1_s1):
            hp = np.clip(pos_u, 0, len(t1_s1) - 1)
            has = t1_s1[hp] == uniq_s1
        else:
            has = np.zeros(n_ent, bool)
        for e in np.flatnonzero(has):
            gslice = slice(int(starts[e]), int(starts[e] + cnts[e]))
            lo_e = int(t1_ind[hp[e]])
            hi_e = int(t1_ind[hp[e] + 1])
            cand[gslice] = np.isin(gt_ot[gslice], t1_oth[lo_e:hi_e])
        miss1 = ~cand
        recovered = miss1 & hit80
        L("--- 4. TRY1 CROSS-TAB ---")
        L(f"  try1 candidates cover {int(cand.sum()):,}/{n_gt:,} GT pairs "
          f"({cand.mean()*100:.2f}%)")
        L(f"  of try1's {int(miss1.sum()):,} missed pairs, the NEW pool "
          f"delivers {int(recovered.sum()):,} "
          f"({recovered.sum()/max(int(miss1.sum()),1)*100:.2f}%)")
        L()

    L("--- inputs ---")
    L(f"  counts: {counts['totals']['uncapped']:,} uncapped / "
      f"{counts['totals']['post_cap']:,} post-cap / "
      f"{counts['totals']['budget_kept']:,} kept by try1's budget")
    L(f"  elapsed: {time.time()-t0:.0f}s")

    out_dir = N.TRY2_DIR / "output"
    out_dir.mkdir(exist_ok=True)
    out_path = out_dir / "phase0_report.txt"
    out_path.write_text("\n".join(lines) + "\n")
    print(f"\n[analyze] wrote {out_path}")


if __name__ == "__main__":
    main()
